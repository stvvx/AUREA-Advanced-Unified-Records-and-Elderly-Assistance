-- Compatibility phase: retain users.id and legacy profile columns.
-- All existing application, reservation, chat and feedback foreign keys stay valid.
BEGIN;

ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS token TEXT,
  ADD COLUMN IF NOT EXISTS ip_address TEXT,
  ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'Active',
  ADD COLUMN IF NOT EXISTS spouse TEXT,
  ADD COLUMN IF NOT EXISTS monthly_income NUMERIC(12,2),
  ADD COLUMN IF NOT EXISTS category TEXT,
  ADD COLUMN IF NOT EXISTS digital_signature TEXT,
  ADD COLUMN IF NOT EXISTS osca_id_number VARCHAR(100);

CREATE TABLE IF NOT EXISTS public.seniors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE REFERENCES public.users(id) ON DELETE CASCADE,
  last_name TEXT,
  first_name TEXT,
  middle_name TEXT,
  contact TEXT,
  address TEXT,
  email TEXT,
  avatar_url TEXT,
  gender TEXT,
  civil_status TEXT,
  spouse TEXT,
  signature TEXT,
  children JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(children) = 'array'),
  birth_certificate TEXT,
  monthly_income NUMERIC(12,2) CHECK (monthly_income >= 0),
  category TEXT,
  dob DATE NOT NULL,
  osca_id_number VARCHAR(100),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.seniors ENABLE ROW LEVEL SECURITY;
-- Remove old copies while backfilling so the migration is safe to rerun.
DROP TRIGGER IF EXISTS aurea_users_to_seniors ON public.users;
DROP TRIGGER IF EXISTS aurea_seniors_to_users ON public.seniors;

-- Only the backend service role / SQL editor can access seniors directly.
-- Never copy password hashes, tokens or IP addresses into seniors.

CREATE OR REPLACE FUNCTION public.aurea_parse_senior_dob(value TEXT)
RETURNS DATE LANGUAGE plpgsql IMMUTABLE SET search_path = public AS $$
BEGIN
  IF trim(value) ~ '^\d{4}-\d{2}-\d{2}$' THEN
    RETURN make_date(split_part(trim(value), '-', 1)::int,
                     split_part(trim(value), '-', 2)::int,
                     split_part(trim(value), '-', 3)::int);
  ELSIF trim(value) ~ '^\d{1,2}/\d{1,2}/\d{4}$' THEN
    RETURN make_date(split_part(trim(value), '/', 3)::int,
                     split_part(trim(value), '/', 1)::int,
                     split_part(trim(value), '/', 2)::int);
  END IF;
  RETURN NULL;
EXCEPTION WHEN datetime_field_overflow OR invalid_datetime_format OR invalid_text_representation THEN
  RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION public.aurea_sync_user_senior(profile JSONB)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  birth_date DATE := aurea_parse_senior_dob(profile->>'dob');
  today_manila DATE := (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Manila')::date;
  senior_age INT;
BEGIN
  senior_age := extract(year FROM age(today_manila, birth_date));
  IF lower(trim(coalesce(profile->>'role', 'user'))) NOT IN ('user', 'senior', 'senior citizen')
     OR birth_date IS NULL OR senior_age < 60 THEN
    -- Retain historical profile information when a role/DOB changes.
    UPDATE seniors SET is_active = FALSE, updated_at = now()
      WHERE user_id = (profile->>'id')::bigint;
    RETURN;
  END IF;
  INSERT INTO seniors (user_id, last_name, first_name, middle_name, contact, address,
    email, avatar_url, gender, civil_status, spouse, signature, children,
    birth_certificate, monthly_income, category, dob, osca_id_number, is_active)
  VALUES ((profile->>'id')::bigint, profile->>'last_name', profile->>'first_name',
    profile->>'middle_name', profile->>'contact', profile->>'address', profile->>'email',
    profile->>'avatar_url', profile->>'gender', profile->>'civil_status',
    coalesce(profile->>'spouse', profile->>'spouse_name'),
    coalesce(nullif(profile->>'digital_signature', ''), nullif(profile->>'signature', ''),
             nullif(profile->>'signature_url', ''), profile->>'digital_signature_url'),
    coalesce(nullif(profile->'children', 'null'::jsonb), '[]'::jsonb),
    coalesce(profile->>'birth_certificate', profile->>'birthcert'),
    nullif(profile->>'monthly_income', '')::numeric,
    coalesce(nullif(profile->>'category', ''), 'Not Specified'), birth_date, profile->>'osca_id_number', TRUE)
  ON CONFLICT (user_id) DO UPDATE SET
    last_name = EXCLUDED.last_name, first_name = EXCLUDED.first_name,
    middle_name = EXCLUDED.middle_name, contact = EXCLUDED.contact,
    address = EXCLUDED.address, email = EXCLUDED.email, avatar_url = EXCLUDED.avatar_url,
    gender = EXCLUDED.gender, civil_status = EXCLUDED.civil_status,
    spouse = EXCLUDED.spouse, signature = EXCLUDED.signature, children = EXCLUDED.children,
    birth_certificate = EXCLUDED.birth_certificate, monthly_income = EXCLUDED.monthly_income,
    category = EXCLUDED.category, dob = EXCLUDED.dob, osca_id_number = EXCLUDED.osca_id_number,
    is_active = TRUE, updated_at = now();
END;
$$;

CREATE OR REPLACE FUNCTION public.aurea_users_to_seniors()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF pg_trigger_depth() > 1 THEN RETURN NEW; END IF;
  PERFORM aurea_sync_user_senior(to_jsonb(NEW));
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.aurea_seniors_to_users()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  account public.users%ROWTYPE;
  patch JSONB;
  assignments TEXT;
BEGIN
  IF pg_trigger_depth() > 1 THEN RETURN NEW; END IF;
  IF TG_OP = 'UPDATE' THEN
    IF NEW.user_id IS DISTINCT FROM OLD.user_id OR NEW.id IS DISTINCT FROM OLD.id THEN
      RAISE EXCEPTION 'Senior record identifiers cannot be changed.';
    END IF;
  END IF;
  SELECT * INTO account FROM users WHERE id = NEW.user_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Create the user account before its senior profile.'; END IF;
  IF lower(trim(coalesce(to_jsonb(account)->>'role', 'user'))) NOT IN ('user', 'senior', 'senior citizen') THEN
    RAISE EXCEPTION 'Staff and admin accounts cannot be assigned a senior profile.';
  END IF;
  IF NEW.dob > ((CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Manila')::date - INTERVAL '60 years')::date THEN
    RAISE EXCEPTION 'Senior citizen profiles require an age of at least 60.';
  END IF;
  NEW.updated_at := now();
  patch := to_jsonb(NEW) - ARRAY['id','user_id','created_at','updated_at','is_active'];
  -- Preserve the existing account DOB format/type for old clients.
  patch := patch || jsonb_build_object('dob', CASE
    WHEN coalesce(to_jsonb(account)->>'dob', '') LIKE '%/%'
      THEN to_char(NEW.dob, 'MM/DD/YYYY') ELSE to_char(NEW.dob, 'YYYY-MM-DD') END,
    'digital_signature', NEW.signature, 'signature_url', NEW.signature,
    'digital_signature_url', NEW.signature);
  -- Only assign columns actually present in users; optional legacy aliases vary.
  SELECT string_agg(format('%I = (jsonb_populate_record(u, $1)).%I', a.attname, a.attname), ', ')
    INTO assignments FROM pg_attribute a
    WHERE a.attrelid = 'public.users'::regclass AND a.attnum > 0 AND NOT a.attisdropped
      AND a.attgenerated = '' AND patch ? a.attname;
  EXECUTE 'UPDATE public.users u SET ' || assignments || ' WHERE id = $2'
    USING patch, NEW.user_id;
  RETURN NEW;
END;
$$;

-- Backfill before installing triggers, preserving existing user IDs.
SELECT public.aurea_sync_user_senior(to_jsonb(u)) FROM public.users u;

DROP TRIGGER IF EXISTS aurea_users_to_seniors ON public.users;
CREATE TRIGGER aurea_users_to_seniors AFTER INSERT OR UPDATE ON public.users
  FOR EACH ROW EXECUTE FUNCTION public.aurea_users_to_seniors();
DROP TRIGGER IF EXISTS aurea_seniors_to_users ON public.seniors;
CREATE TRIGGER aurea_seniors_to_users BEFORE INSERT OR UPDATE ON public.seniors
  FOR EACH ROW EXECUTE FUNCTION public.aurea_seniors_to_users();

-- Trigger helpers must not be callable as anonymous PostgREST RPCs.
REVOKE ALL ON FUNCTION public.aurea_sync_user_senior(JSONB) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.aurea_users_to_seniors() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.aurea_seniors_to_users() FROM PUBLIC;
NOTIFY pgrst, 'reload schema';
COMMIT;
